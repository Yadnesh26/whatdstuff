  labels.add('mask', panel, 'Function patterns are never masked', [mx(21), my(3), zf], 70, 100);

  labels.add('scan', panel, 'Three finders, four corners', [mx(25), my(24), zf], -40, 76);
  labels.add('scan', phone, 'Unmask, then Reed–Solomon', [0.05, -0.2, 0.03], 35, 86);

