  labels.add('finder', panel, 'No finder — that sets which way is up', [mx(21), my(21), zf], 265, 90);

  labels.add('grid', panel, 'Timing pattern — the ruler', [mx(12), my(6), zf], 35, 96);
  labels.add('grid', panel, 'Alignment pattern — 5 × 5', [mx(18), my(18), zf], -150, 90);
  labels.add('grid', panel, 'Counts the module pitch', [mx(6), my(12), zf], -30, 96);

  labels.add('format', panel, 'Format information — 15 bits', [mx(21), my(8), zf], 150, 92);
  labels.add('format', panel, 'The same 15 bits, written twice', [mx(8), my(21), zf], -60, 92);
  labels.add('format', panel, 'Always-dark module', [mx(8), my(17), zf], -14, 124);

  labels.add('data', panel, 'Mode: byte — 0100', [mx(24), my(23), zf], 25, 88);
  labels.add('data', railGroup, '16 data codewords', [-0.42, 0.07, 0.02], 60, 82);
  labels.add('data', panel, 'The message itself sits here', [mx(17), my(17), zf], 25, 88);

  labels.add('ec', railGroup, '28 Reed–Solomon codewords', [0.36, 0.07, 0.02], 42, 96);
